-- Fix: "column reference gift_id is ambiguous"
--
-- `send_live_gift` is declared as `returns table (gift_id uuid, balance integer)`.
-- Those OUT parameters are plpgsql variables inside the body, so a bare
-- `gift_id` in `on conflict (gift_id)` could mean either the OUT parameter or
-- the `public.gift_claims.gift_id` column. Postgres refuses to guess and throws
-- 42702 at call time (plpgsql only validates statements on first execution, so
-- the migration itself succeeded and the error surfaced when a viewer sent a
-- gift).
--
-- The insert is rewritten as `insert ... select ... where not exists (...)`,
-- which references the column through a table alias and needs no ON CONFLICT
-- inference. `v_gift_id` is freshly generated by the insert above, so the guard
-- is purely defensive and cannot race.

create or replace function public.send_live_gift(
  p_live_id uuid,
  p_receiver_id uuid,
  p_gift_type text,
  p_coins integer,
  p_quantity integer default 1
)
returns table (gift_id uuid, balance integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_sender uuid := auth.uid();
  v_balance integer;
  v_paid_balance integer;
  v_free integer;
  v_from_free integer;
  v_from_paid integer;
  v_gift_id uuid;
  v_diamonds integer;
  v_amount numeric(10, 2);
begin
  if v_sender is null then
    raise exception 'not_signed_in' using errcode = '42501';
  end if;
  if p_receiver_id is null or p_receiver_id = v_sender then
    raise exception 'invalid_receiver' using errcode = '22023';
  end if;
  if p_coins is null or p_coins <= 0 or p_coins > 100000 then
    raise exception 'invalid_amount' using errcode = '22023';
  end if;
  if p_quantity is null or p_quantity < 1 or p_quantity > 100 then
    raise exception 'invalid_quantity' using errcode = '22023';
  end if;

  -- Lock the authenticated sender's wallet; sender_id is never accepted from
  -- the client and is always the UUID returned by auth.uid().
  select uc.balance, coalesce(uc.paid_balance, 0)
    into v_balance, v_paid_balance
    from public.user_coins as uc
   where uc.user_id = v_sender
     for update;

  if v_balance is null or v_balance < p_coins then
    raise exception 'insufficient_coins' using errcode = 'P0001';
  end if;

  -- Spend free starter coins first; only paid coins generate creator earnings.
  v_free := greatest(v_balance - v_paid_balance, 0);
  v_from_free := least(v_free, p_coins);
  v_from_paid := p_coins - v_from_free;

  update public.user_coins as uc
     set balance = uc.balance - p_coins,
         paid_balance = greatest(coalesce(uc.paid_balance, 0) - v_from_paid, 0),
         total_spent = uc.total_spent + p_coins,
         updated_at = now()
   where uc.user_id = v_sender
  returning uc.balance into v_balance;

  v_diamonds := v_from_paid / 2;
  v_amount := round(v_diamonds * 0.01, 2);

  -- A nullable live_id records gifts sent without an associated live session.
  insert into public.live_gifts (
    live_id, sender_id, receiver_id, gift_type, coins, quantity, diamonds
  ) values (
    p_live_id, v_sender, p_receiver_id, p_gift_type, p_coins, p_quantity, v_diamonds
  ) returning id into v_gift_id;

  insert into public.user_coins as uc (user_id, balance, total_earned, diamonds)
  values (p_receiver_id, 0, p_coins, v_diamonds)
  on conflict (user_id) do update
    set total_earned = uc.total_earned + excluded.total_earned,
        diamonds = uc.diamonds + excluded.diamonds,
        updated_at = now();

  insert into public.user_balance as ub (user_id, diamonds, total_earned)
  values (p_receiver_id, v_diamonds, v_amount)
  on conflict (user_id) do update
    set diamonds = ub.diamonds + excluded.diamonds,
        total_earned = ub.total_earned + excluded.total_earned,
        updated_at = now();

  -- One claim row per gift, so a gift can never be double-credited.
  -- Written as an anti-join so `gift_id` is always a qualified column
  -- reference and can never collide with this function's OUT parameter.
  insert into public.gift_claims (gift_id, user_id, diamonds, amount, gift, coins)
  select v_gift_id, p_receiver_id, v_diamonds, v_amount, p_gift_type, p_coins
   where not exists (
     select 1
       from public.gift_claims as gc
      where gc.gift_id = v_gift_id
   );

  return query select v_gift_id, v_balance;
end;
$$;

revoke all on function public.send_live_gift(uuid, uuid, text, integer, integer) from public;
grant execute on function public.send_live_gift(uuid, uuid, text, integer, integer) to authenticated;
